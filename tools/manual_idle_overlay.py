"""Build an in-memory strategy overlay for exact Rev A; never writes a BIN.

This is development source, with proposed gains/cold air not truck validated.
Address-register snapshot remains Rev A until a later authorized BIN release.
"""
from __future__ import annotations
import hashlib
from pathlib import Path
from manual_idle_asm import assemble
from factory_rom_decode import decode

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'source/manual_idle/manual_idle.asm'
EXPECTED_SHA = 'd771e824686d086986ee0bdef37697bfc63274071a13b79fc4ba59746644923e'
RETIRED = ((0x92a4, 0x93c5), (0x9411, 0x983d), (0x989c, 0xa3fa))
# Full-byte preservation includes the reset guard, homing request, conversion,
# service escapes, phase/enable/count logic, scheduler and hardware writers.
PRESERVED = ((0x4000, 0x4006), (0x4008, 0x92a4), (0x93c5, 0x9411),
             (0x983d, 0x989c), (0xa3fa, 0xffc0), (0xffc0, 0x10000))


def layout_header(assembly=None):
    assembly = assembly or assemble(SOURCE)
    lines = ['/* Generated by tools/manual_idle_overlay.py; simulation layout. */',
             '#ifndef MANUAL_IDLE_LAYOUT_H', '#define MANUAL_IDLE_LAYOUT_H']
    for name, value in assembly.symbols.items():
        if name.startswith('cal_') or name in ('integral', 'follower', 'start_air',
                'start_div', 'qualify', 'signature', 'error', 'p_word', 'scratch'):
            lines.append(f'#define MI_{name.upper()} 0x{value:04x}u')
    return '\n'.join(lines + ['#endif', ''])


def overlay(original: bytes):
    if len(original) != 65536 or hashlib.sha256(original).hexdigest() != EXPECTED_SHA:
        raise ValueError('Requires the exact 64K Rev A image; refusing an unreviewed baseline')
    assembly = assemble(SOURCE)
    image = bytearray(original)
    for lo, hi in RETIRED:
        image[lo:hi] = b'\xff' * (hi - lo)
    for address, value in assembly.memory.items():
        if not any(lo <= address < hi for lo, hi in RETIRED):
            raise ValueError(f'Source escapes replacement allocation at {address:04X}')
        image[address] = value
    # Existing boot/reset call sites keep their ABI but no longer seed or
    # restore either factory bank. 93C5's phase reset remains unchanged.
    init = assembly.symbols['mi_init'].to_bytes(2, 'big')
    for address in (0x92a4, 0x92f1):
        image[address:address + 3] = b'\x7e' + init
    for lo, hi in PRESERVED:
        if image[lo:hi] != original[lo:hi]:
            raise AssertionError(f'Preservation failure: {lo:04X}..{hi:04X}')
    checksum = sum(image[0x4008:]) & 65535
    image[0x4006:0x4008] = checksum.to_bytes(2, 'big')
    # Exclude deliberate data from executable sources, including FF bytes.
    live_bytes = {a + offset for a in assembly.instructions
                  for offset in range(len(decode(lambda x, n: image[x:x+n], a).data))}
    live_bytes.update(range(0x92a4, 0x92a7)); live_bytes.update(range(0x92f1, 0x92f4))
    retired_code = {a for lo, hi in RETIRED for a in range(lo, hi)} - live_bytes
    return bytes(image), assembly, retired_code


if __name__ == '__main__':
    # Header generation needs no private image and creates no firmware file.
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write-layout', action='store_true')
    a = p.parse_args()
    header = layout_header()
    target = ROOT / 'source/manual_idle/manual_idle_layout.h'
    if a.write_layout:
        target.write_text(header)
    elif target.read_text() != header:
        raise SystemExit('Stale manual-idle layout header')
    x = assemble(SOURCE)
    print(f'{len(x.instructions)} decoded HC11 instructions; {len(x.memory)} code/data bytes; no BIN written')
