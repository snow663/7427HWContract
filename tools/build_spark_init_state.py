def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def resolve_path(path: str | Path) -> Path:
    p = Path(path)
    return p if p.is_absolute() else repo_root() / p


def touch_required(path: str | Path) -> None:
    p = resolve_path(path)
    if not p.exists():
        raise FileNotFoundError(p)


def write_csv(out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    fields = ["stage", "pc", "mnemonic", "operands", "state_symbol", "state_address", "read_or_write", "value_source", "routine_label", "init_context", "before_first_la906", "crank_or_run", "candidate_role", "required_for_minimal_os", "confidence", "notes"]
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(INIT_ROWS)


