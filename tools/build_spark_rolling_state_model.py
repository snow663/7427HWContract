def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", default="source/31/BMHM_HAC_ORG_7100_to_end.asm")
    ap.add_argument("--la906", default="maps/contracts/spark_la906_output_sequence.csv")
    ap.add_argument("--timebase", default="maps/contracts/spark_timebase_period_contract.csv")
    ap.add_argument("--equation", default="maps/contracts/spark_conversion_equation.csv")
    ap.add_argument("--out-md", required=True)
    ap.add_argument("--out-csv", required=True)
    args = ap.parse_args()

    for dep in [args.source, args.la906, args.timebase, args.equation]:
        touch_required(dep)
    write_csv(resolve_path(args.out_csv))
    write_md(resolve_path(args.out_md))
    print(f"rolling state rows: {len(ROLLING_ROWS)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
